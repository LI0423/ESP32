#!/usr/bin/env bash
# Write main/admin_cert.h, which provisioning.c includes for the HTTPS admin
# server. The header embeds a private key, so it is gitignored. Re-running
# replaces the local certificate.
set -euo pipefail

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
OUT="$ROOT/main/admin_cert.h"

if ! command -v openssl >/dev/null 2>&1; then
    echo "gen_admin_cert: openssl is required" >&2
    exit 1
fi

WORKDIR="$(mktemp -d "${TMPDIR:-/tmp}/deskpal-cert.XXXXXX")"
trap 'rm -rf "$WORKDIR"' EXIT
umask 077

openssl req -x509 -newkey rsa:2048 -sha256 -nodes \
    -keyout "$WORKDIR/key.pem" \
    -out "$WORKDIR/cert.pem" \
    -days 3650 \
    -subj "/CN=deskpal.local" \
    -addext "basicConstraints=critical,CA:FALSE" \
    -addext "keyUsage=critical,digitalSignature,keyEncipherment" \
    -addext "extendedKeyUsage=serverAuth" \
    -addext "subjectAltName=DNS:deskpal.local,IP:192.168.4.1"

openssl x509 -in "$WORKDIR/cert.pem" -noout -subject -ext subjectAltName >/dev/null
openssl pkey -in "$WORKDIR/key.pem" -noout >/dev/null

c_string() {
    sed 's/\r$//; s/\\/\\\\/g; s/"/\\"/g; s/^/    "/; s/$/\\n"/' "$1"
}

{
    echo "/* Generated by tools/gen_admin_cert.sh. Local TLS material; do not commit. */"
    echo "#pragma once"
    echo
    echo "static const unsigned char admin_server_cert[] ="
    c_string "$WORKDIR/cert.pem"
    echo ";"
    echo
    echo "static const unsigned char admin_server_key[] ="
    c_string "$WORKDIR/key.pem"
    echo ";"
} > "$WORKDIR/admin_cert.h"

install -m 600 "$WORKDIR/admin_cert.h" "$OUT"
echo "Wrote $OUT"
